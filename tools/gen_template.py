#!/usr/bin/env python3
"""Embed src/viewer_template.html into src/template_html.h (raw-string chunks, MSVC-safe)."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "..", "src", "viewer_template.html")
dst = os.path.join(here, "..", "src", "template_html.h")
data = open(src, encoding="utf-8").read()
assert ')YT"' not in data
CH = 8000  # MSVC limits a single literal to ~16 KB
parts = []
i = 0
while i < len(data):
    j = min(i + CH, len(data))
    # don't split a UTF-8 sequence (we split str, so chars are whole) - encode per chunk
    parts.append(data[i:j]); i = j
with open(dst, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/gen_template.py from viewer_template.html - do not edit.\n#pragma once\n")
    f.write("static const char* const kTemplateParts[] = {\n")
    for p in parts:
        f.write('u8R"YT(' + p + ')YT",\n')
    f.write("};\n")
print("wrote", dst, len(parts), "chunks")
